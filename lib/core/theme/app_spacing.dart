/// Centralized spacing tokens for consistent layout across the app.
///
/// Widgets should use these instead of arbitrary numeric padding/gap values.
class AppSpacing {
  AppSpacing._();

  static const double xxs = 4;
  static const double xs = 8;
  static const double sm = 12;
  static const double md = 16;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 48;
  static const double section = 40;

  // Common page-level values.
  static const double screenHorizontal = 16;
  static const double screenVertical = 24;
  static const double cardPadding = 16;
  static const double inputSpacing = 12;
  static const double sectionSpacing = 32;
}
